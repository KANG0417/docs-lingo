export const buildClaudeFullTranslationUserPrompt = ({
  chunkText,
  chunkIndex,
  totalChunks,
}: {
  chunkText: string;
  chunkIndex: number;
  totalChunks: number;
}): string => {
  const chunkNotice =
    totalChunks > 1
      ? `이 문서는 길어서 ${totalChunks}개로 나누어 번역합니다. 지금은 ${chunkIndex + 1}번째 조각입니다. 이 조각 안의 내용만 번역하고, 앞뒤 조각에 대한 안내나 요약은 추가하지 마세요.`
      : "";

  return [
    "다음 기술 문서 본문을 생략 없이 전체 한국어로 번역하세요. 요약이 아니라 완전 번역입니다.",
    "원문에서 빈 줄로 구분된 '제목' 블록과 '본문' 블록의 순서·경계를 그대로 유지하세요.",
    "제목 블록(한 줄짜리 소제목)은 짧은 한국어 제목으로, 본문 블록은 문장을 빠짐없이 한국어로 옮기세요.",
    chunkNotice,
    "",
    FULL_TRANSLATION_MARKUP_RULES,
    "",
    "<document>",
    chunkText,
    "</document>",
    "",
    "번역된 본문만 출력하세요. 다른 설명이나 따옴표, 코드블록 표시를 덧붙이지 마세요.",
  ].join("\n");
};
